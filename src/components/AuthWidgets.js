// 3 nút đăng nhập mạng xã hội. Google & GitHub dùng Firebase popup; Discord chưa hỗ trợ.
export function SocialButtons({ onSuccess, onError, disabled }) {
  const { loginWithProvider } = useAuth();

  async function handle(name) {
    try {
      const result = await loginWithProvider(name);
      onSuccess(result.user);
    } catch (err) {
      if (err.code === 'auth/popup-closed-by-user' || err.code === 'auth/cancelled-popup-request') return;
      if (err.code === 'auth/account-exists-with-different-credential') {
        onError('Email này đã đăng ký bằng phương thức khác. Hãy đăng nhập bằng phương thức đó.');
      } else {
        onError('Đăng nhập thất bại: ' + err.message);
      }
    }
  }

  return (
    <div className="social-row">
      <button type="button" className="social-btn" title="Google" aria-label="Đăng nhập bằng Google" disabled={disabled} onClick={() => handle('google')}>
        <GoogleIcon />
      </button>
      <button type="button" className="social-btn" title="GitHub" aria-label="Đăng nhập bằng GitHub" disabled={disabled} onClick={() => handle('github')}>
        <GithubIcon />
      </button>
      <button type="button" className="social-btn" title="Discord (sắp ra mắt)" aria-label="Discord - sắp ra mắt" disabled>
        <DiscordIcon />
      </button>
    </div>
  );
}
